<?php

declare(strict_types=1);

namespace OznerOmali\LaravelToI18nextLangParser\Support;

/**
 * Renders converted namespaces as a TypeScript declaration i18next can type `t()` against.
 *
 * Values are emitted as string literals rather than `string`, because i18next reads them to type the
 * interpolation options: `t('orders:ready', { orderId })` is checked against `{{orderId}}`.
 */
class TypeScriptGenerator
{
    /**
     * @param  array<string, array<array-key, mixed>>  $namespaces  namespace => converted lines
     */
    public function generate(array $namespaces, string $locale): string
    {
        ksort($namespaces);

        return "// Generated by `php artisan lang:to-i18next` from the [{$locale}] translations. Do not edit.\n"
            ."// See https://www.i18next.com/overview/typescript for wiring it into CustomTypeOptions.\n\n"
            .'export interface Resources '.$this->object($namespaces, 0).";\n\n"
            ."export default Resources;\n";
    }

    /**
     * @param  array<array-key, mixed>  $lines
     */
    private function object(array $lines, int $depth): string
    {
        if ($lines === []) {
            return '{}';
        }

        $indent = str_repeat('  ', $depth + 1);
        $body = '';

        foreach ($lines as $key => $value) {
            $body .= $indent.$this->literal((string) $key).': '.$this->type($value, $depth + 1).";\n";
        }

        return "{\n{$body}".str_repeat('  ', $depth).'}';
    }

    private function type(mixed $value, int $depth): string
    {
        return match (true) {
            is_array($value) && array_is_list($value) => 'readonly ['.implode(', ', array_map(
                fn (mixed $item): string => $this->type($item, $depth),
                $value,
            )).']',
            is_array($value) => $this->object($value, $depth),
            is_string($value) => $this->literal($value),
            is_int($value), is_float($value) => (string) $value,
            is_bool($value) => $value ? 'true' : 'false',
            default => 'null',
        };
    }

    /**
     * A JSON string is a valid TypeScript string literal.
     */
    private function literal(string $value): string
    {
        return (string) json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    }
}
